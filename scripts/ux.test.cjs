const {chromium}=require('playwright');
const assert=require('node:assert/strict');
const {spawn}=require('node:child_process');
const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'..'),out=path.join(root,'.artifacts');
fs.mkdirSync(out,{recursive:true});
const port=Number(process.env.UX_TEST_PORT||18861),base=`http://127.0.0.1:${port}/`;
const server=spawn(process.env.PYTHON||(process.platform==='win32'?'python':'python3'),['scripts/preview.py','--port',String(port)],{cwd:root,stdio:'ignore'});
let browser,checks=0;const errors=[];
function check(value,message){assert(value,message);checks++;}
(async()=>{try{
  for(let i=0;i<100;i++){try{if((await fetch(base)).ok)break;}catch{}if(i===99)throw Error('Preview failed');await new Promise(r=>setTimeout(r,100));}
  browser=await chromium.launch({headless:true,args:['--renderer-process-limit=2']});
  for(const lang of ['nl','en'])for(const width of [320,390,768,1440]){
    const page=await browser.newPage({viewport:{width,height:900}});
    page.on('pageerror',e=>errors.push(e.message));
    await page.route('**/*',route=>new URL(route.request().url()).hostname==='127.0.0.1'?route.continue():route.abort());
    await page.goto(base+'collectie.html?lang='+lang);
    await page.locator('.product').first().waitFor();
    const total=await page.locator('.product').count();
    await page.locator('#product-search').fill(lang==='nl'?'  TAFEL  ':'  STAND  ');
    check(await page.locator('.product').count()>0,'Whitespace and case tolerant search');
    check(new URL(page.url()).searchParams.get('search')===(lang==='nl'?'TAFEL':'STAND'),'Search in shareable URL');
    await page.reload();await page.locator('.product').first().waitFor();
    check((await page.locator('#product-search').inputValue()).trim()===(lang==='nl'?'TAFEL':'STAND'),'Search survives reload');
    await page.locator('#product-search').fill('no-such-object-xyz');
    check(await page.locator('.product').count()===0,'Empty results');
    await page.locator('#empty-reset').click();
    check(await page.locator('.product').count()===total,'Empty-state action restores all products');
    check(await page.locator('#product-search').evaluate(n=>n===document.activeElement),'Reset returns search focus');
    await page.locator('#product-category').selectOption('pots');
    check(await page.locator('.product').count()<total,'Category filters products');
    await page.locator('#reset-filters').click();
    check(await page.locator('#product-sort').isHidden(),'Secondary controls start collapsed');
    await page.locator('.browse-options summary').click();
    await page.locator('#product-sort').selectOption('price-asc');
    await page.locator('.browse-options summary').click();
    const prices=await page.locator('.product-price strong').allTextContents();
    const numbers=prices.filter(p=>/\d/.test(p)).map(p=>Number(p.replace(/[^0-9,.-]/g,'').replace(',','.')));
    check(numbers.every((p,i)=>!i||p>=numbers[i-1]),'Prices sorted ascending');
    check(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),'Collection fits screen');
    if(width===390||width===1440)await page.screenshot({path:path.join(out,`ux-collection-${lang}-${width}.png`)});
    if(width<961){
      await page.locator('.menu-toggle').click();
      check(await page.locator('#main-nav a').first().evaluate(n=>n===document.activeElement),'Menu focus enters navigation');
      await page.keyboard.press('Escape');
      check(await page.locator('.menu-toggle').getAttribute('aria-expanded')==='false','Escape closes menu');
      check(await page.locator('.menu-toggle').evaluate(n=>n===document.activeElement),'Escape restores toggle focus');
    }
    const first=page.locator('.product-art').first();
    await first.click();await page.locator('#product-dialog[open]').waitFor();
    await page.goBack();await page.locator('#product-dialog[open]').waitFor({state:'hidden'});
    check(page.url().includes('collectie.html'),'Back dismisses product without leaving collection');
    await page.goForward();await page.locator('#product-dialog[open]').waitFor();
    check(await page.locator('#product-dialog').evaluate(n=>n.open),'Forward reopens product');
    await page.locator('#product-dialog .dialog-close').click();
    await page.waitForURL(url=>!url.searchParams.has('product'));
    await page.goto(base+'collectie.html?lang='+lang+'&product=bonsai-classic-table&finish=grey');
    await page.locator('#product-dialog[open]').waitFor();
    check(await page.locator('#product-form [name=finish]').inputValue()==='grey','Grey deep link retains grey');
    await page.locator('[data-image-index="1"]').click();
    check(await page.locator('#product-form [name=finish]').inputValue()==='grey','Browsing photographs preserves chosen finish');
    check(await page.locator('.product-dimensions').isHidden(),'Extra specifications start collapsed');
    await page.locator('.product-description summary').click();
    check(await page.locator('#product-dialog .dialog-close').evaluate(n=>{const r=n.getBoundingClientRect();return r.top>=0&&r.bottom<=innerHeight;}),'Close control stays on screen when reading details');
    check(await page.locator('.product-dimensions').isVisible(),'Specifications remain easy to open');
    await page.locator('.product-description summary').click();
    check(await page.locator('#product-dialog').evaluate(n=>n.scrollWidth<=n.clientWidth+1),'Product dialog fits screen');
    if(width===390||width===1440)await page.screenshot({path:path.join(out,`ux-product-${lang}-${width}.png`)});
    await page.locator('#product-form button[type=submit]').click();
    await page.locator('#product-dialog[open]').waitFor({state:'hidden'});
    await page.locator('.selection-toggle').click();
    await page.locator('#inquiry-form button[type=submit]').click();
    const mail=page.locator('.request-actions a[href^="mailto:"]');
    const href=await mail.getAttribute('href');
    check(decodeURIComponent(href).includes(lang==='nl'?'Mijn selectie':'My selection'),'Email contains overview');
    check(decodeURIComponent(href).includes(lang==='nl'?'grijs':'grey'),'Email retains selected grey finish');
    check(await page.locator('#request-text').evaluate(n=>n===document.activeElement),'Generated overview receives focus');
    await page.close();
  }
  const page=await browser.newPage();
  await page.route('**/assets/catalogue.json*',route=>route.fulfill({status:503,body:'Unavailable'}));
  await page.goto(base+'collectie.html?lang=en&search=stand');
  await page.locator('#retry-load').waitFor();
  check((await page.locator('.load-error').innerText()).includes('could not be loaded'),'Load failure has English recovery message');
  await page.unroute('**/assets/catalogue.json*');
  await page.locator('#retry-load').click();await page.locator('.product').first().waitFor();
  check(await page.locator('#product-search').inputValue()==='stand','Retry preserves search');
  assert.deepEqual(errors,[]);
  console.log(JSON.stringify({status:'passed',checks,viewports:[320,390,768,1440],languages:['nl','en']},null,2));
}catch(e){console.error(e);process.exitCode=1;}finally{if(browser)await browser.close();server.kill();}})();
